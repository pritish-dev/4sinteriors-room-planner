"""Build assets/colours.js: the colour options each catalogue product is actually sold in.

Source: the 4S Orders app (github.com/pritish-dev/4s-orders) —
  catalog/catalog.json  "map": product -> price-book item ids
  index.html            <script id="4s-price-data">: the price book (item name, shade, ...)
Only items with an explicit `shade` in the price book are used, so a product gets a
colour picker only when its real colour list is known.

Usage: python3 tools/build_colours.py /path/to/4s-orders
"""
import json, re, sys, os

ORD = sys.argv[1]
OUT = os.path.join(os.path.dirname(__file__), '..', 'room-planner-android/app/src/main/assets/colours.js')

# Approximate swatch colours for the shade names used in the price book.
HEX = {
  'ash': '#9c9a96', 'blue': '#3f5f8f', 'forest': '#3d5a45', 'oat': '#cbbd9f', 'rust': '#9a4b2f',
  'saloman': '#c98b72', 'salmon': '#d9907a', 'black': '#262626', 'brown': '#6b4a35', 'grey': '#7d7f84',
  'gray': '#7d7f84', 'charcoal': '#3c3d40', 'anthracite': '#45474b', 'anthricite': '#45474b', 'camel': '#b08455',
  'truffle': '#6e5a4e', 'chocolate': '#4e3426', 'choclate': '#4e3426', 'khaki': '#a99b72', 'purple': '#5e4a6e',
  'beige': '#d8c8aa', 'biege': '#d8c8aa', 'toffee': '#8a5a3a', 'peanut': '#b68a5e', 'mint': '#a8cbb7',
  'ruben blue': '#2f4f7f', 'marine blue': '#24466e', 'marineblue': '#24466e', 'terra brown': '#7a4a32',
  'gordion': '#8a7f73', 'grigio': '#8d8d8a', 'lidya': '#d9d2c6', 'afyon': '#e7e1d6', 'parlek': '#cfc6b8',
  'marlot': '#a57a52', 'rubberwood': '#b48a5e', 'white': '#efede8', 'ivory': '#eee6d3', 'cream': '#ece2cc',
  'walnut': '#6b4a33', 'oak': '#b48a5e', 'wenge': '#3e2c22', 'red': '#9b2a2a', 'green': '#4b6b4f',
}

def hex_of(name):
  n = name.lower()
  n = re.sub(r'\((syn|fabric)\)', '', n)
  n = re.sub(r'^hmr|roundtop$|round top$', '', n.replace(' ', '')) if 'roundtop' in n.replace(' ', '') else n
  parts = [p.strip() for p in re.split(r'\+', n) if p.strip()]
  out = []
  for p in parts:
    key = re.sub(r'\s+', ' ', p).strip()
    h = HEX.get(key) or HEX.get(key.replace(' ', ''))
    if not h:
      for k, v in HEX.items():
        if k in key.replace(' ', '') or k in key:
          h = v; break
    out.append(h)
  return [h for h in out if h] or None

def label(name):
  n = re.sub(r'\s*\+\s*', ' + ', name.strip())
  m = re.match(r'^HMR(\w+?)RoundTop$', n)
  if m: return m.group(1) + ' round top (HMR)'
  m = re.match(r'^Rubberwood(\w+?)RoundTop$', n)
  if m: return m.group(1) + ' round top (rubberwood)'
  return n

html = open(os.path.join(ORD, 'index.html'), encoding='utf-8').read()
book = json.loads(re.search(r'<script[^>]*id="4s-price-data"[^>]*>(.*?)</script>', html, re.S).group(1))
byid = {r['id']: r for r in book}
cat = json.load(open(os.path.join(ORD, 'catalog/catalog.json'), encoding='utf-8'))
mp = cat['map']

# Planner product ids come from the planner's own catalog.js (matched by sub|name).
pc = open(os.path.join(os.path.dirname(__file__), '..', 'room-planner-android/app/src/main/assets/catalog.js'), encoding='utf-8').read()
planner = json.loads(pc[pc.index('['):pc.rindex(']') + 1])
pid = {p['sub'] + '|' + p['name']: p['id'] for p in planner}

out = {}
for key, groups in mp.items():
  if key not in pid: continue
  seen = {}
  for _, ids in groups:
    for i in ids:
      r = byid.get(i)
      if not r or not r.get('shade'): continue
      lab = label(str(r['shade']))
      k = lab.lower().replace(' ', '')
      if k in seen: continue
      hx = hex_of(lab)
      if not hx: continue
      seen[k] = {'n': lab, 'c': hx}
  if len(seen) >= 2:
    out[pid[key]] = list(seen.values())

js = ('/* Generated by tools/build_colours.py from the 4S Orders price book — do not edit by hand.\n'
      '   COLOURS[productId] = [{n: shade name, c: [main hex, second hex for two-tone]}] */\n'
      'window.COLOURS=' + json.dumps(out, separators=(',', ':'), ensure_ascii=False) + ';\n')
open(OUT, 'w', encoding='utf-8').write(js)
print(len(out), 'products with colour options:', ', '.join(next(p['name'] for p in planner if p['id'] == k) for k in out))
